"""An image of a workspace (X03b, ADR-0036 §6; médiathèque, ADR-0040): what Otlet keeps of it,
what it says of it, and its limits."""

from dataclasses import dataclass
from datetime import datetime
from uuid import UUID

# What a person may send: a photo from a phone fits, a poster scanned at 600 dpi does not.
MAX_BYTES = 15 * 1024 * 1024
MAX_PIXELS = 40_000_000  # decoded size: an image that unpacks to more is refused
# What Otlet keeps: no side longer than this, which covers a site's widest picture.
MAX_SIDE = 4096
FORMATS = {"image/jpeg": "jpg", "image/png": "png", "image/webp": "webp"}
# The grid of the médiathèque shows these, never the originals (ADR-0040).
THUMBNAIL_SIDE = 320
THUMBNAIL_EXTENSION = "webp"

# Where an image comes from (ADR-0040): imported or pasted in the editor, imported into the bank
# of images, fetched from a source under a declaration, generated by a model. The last two are
# reserved for what comes next.
ORIGINS = ("editor", "library", "source", "generated")
NAME_MAX = 200
DESCRIPTION_MAX = 500  # it prefills the alternative text of an image block, which has as much
CREDIT_MAX = 300
LICENCE_MAX = 100
URL_MAX = 2000


class MediaError(ValueError):
    """An image refused, with a code the interface names: too_large, not_an_image,
    invalid_name, too_long, invalid_url."""

    def __init__(self, code: str) -> None:
        super().__init__(code)
        self.code = code


@dataclass(frozen=True, slots=True)
class Image:
    """An image as Otlet stores it: decoded, re-encoded without its metadata (GPS position,
    camera, author), turned upright, and no larger than MAX_SIDE."""

    data: bytes
    mime: str  # one of FORMATS
    width: int
    height: int


@dataclass(frozen=True, slots=True)
class Media:
    id: UUID
    sha256: str  # the address of its file
    mime: str
    width: int
    height: int
    size: int  # bytes
    created_at: datetime
    name: str | None = None
    description: str | None = None
    origin: str = "editor"  # one of ORIGINS
    in_bank: bool = False  # kept by a person to be used again (« Banque d'images »)
    credit: str | None = None  # its author, or whom to credit
    licence: str | None = None
    source_url: str | None = None
    thumbnail_sha256: str | None = None


@dataclass(frozen=True, slots=True)
class Entry:
    """An image in the médiathèque, with the number of articles that show it."""

    media: Media
    articles: int


@dataclass(frozen=True, slots=True)
class Usage:
    """An article that shows an image, and in which of its versions."""

    article_id: UUID
    title: str
    status: str
    versions: tuple[int, ...]


@dataclass(frozen=True, slots=True)
class Description:
    """What a person says of an image; an empty text clears it."""

    name: str | None
    description: str | None
    credit: str | None
    licence: str | None
    source_url: str | None


@dataclass(frozen=True, slots=True)
class Outcome:
    """What an action on a selection did: the images done, those failed and why."""

    done: tuple[UUID, ...]
    failed: tuple[tuple[UUID, str], ...]


def _text(value: str | None, limit: int) -> str | None:
    if value is None:
        return None
    cleaned = " ".join(value.split())
    if len(cleaned) > limit:
        raise MediaError("too_long")
    return cleaned or None


def cleaned(description: Description) -> Description:
    """The description as it is kept: spaces tidied, empty texts cleared, limits checked."""
    url = _text(description.source_url, URL_MAX)
    if url is not None and not url.startswith(("https://", "http://")):
        raise MediaError("invalid_url")
    return Description(
        name=_text(description.name, NAME_MAX),
        description=_text(description.description, DESCRIPTION_MAX),
        credit=_text(description.credit, CREDIT_MAX),
        licence=_text(description.licence, LICENCE_MAX),
        source_url=url,
    )
